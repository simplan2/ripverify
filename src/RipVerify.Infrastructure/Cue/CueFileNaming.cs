using System.Text;
using RipVerify.Core.Models;

namespace RipVerify.Infrastructure.Cue;

internal static class CueFileNaming
{
    public const string RepairedSuffix = " [RipVerify Repaired]";
    public const string GeneratedSuffix = " [RipVerify Generated]";

    public static string WithSuffix(string cuePath, string suffix)
    {
        var directory = Path.GetDirectoryName(cuePath) ?? string.Empty;
        var fileName = Path.GetFileNameWithoutExtension(cuePath);
        return Path.Combine(directory, fileName + suffix + ".cue");
    }
}

internal static class CueProvenance
{
    private const string Version = "v0.1.0";
    private const string OriginPrefix = "REM RIPVERIFY_CUE_ORIGIN";
    private static readonly string[] LineSplitArray = new[] { "\r\n", "\n", "\r" };

    public static CueOrigin ResolveOrigin(string cuePath, string content, bool modified)
    {
        if (modified)
        {
            return CueOrigin.Sanitized;
        }

        if (HasSuffix(cuePath, CueFileNaming.RepairedSuffix))
        {
            return CueOrigin.Sanitized;
        }

        var declaredOrigin = ReadDeclaredOrigin(content);
        if (HasSuffix(cuePath, CueFileNaming.GeneratedSuffix))
        {
            return declaredOrigin is CueOrigin.GeneratedFromItoc or
                   CueOrigin.GeneratedFromMetadata or
                   CueOrigin.GeneratedFromTocLookup
                ? declaredOrigin.Value
                : CueOrigin.GeneratedFromMetadata;
        }

        return declaredOrigin ?? CueOrigin.Original;
    }

    public static string BuildHeader(CueOrigin origin)
    {
        var builder = new StringBuilder();
        builder.Append("REM COMMENT \"Generated by RipVerify ").Append(Version).Append("\"\r\n");
        builder.Append("REM RIPVERIFY_CUE_ORIGIN ").Append(origin).Append("\r\n");

        if (origin == CueOrigin.GeneratedFromItoc)
        {
            builder.Append("REM RIPVERIFY_SOURCE_ITOC true\r\n");
        }

        if (origin == CueOrigin.Sanitized)
        {
            builder.Append("REM RIPVERIFY_WAS_REPAIRED true\r\n");
        }

        return builder.ToString();
    }

    private static CueOrigin? ReadDeclaredOrigin(string content)
    {
        var lines = content.Split(LineSplitArray, StringSplitOptions.None);
        foreach (var line in lines)
        {
            var trimmed = line.TrimStart();
            if (!trimmed.StartsWith(OriginPrefix, StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            if (trimmed.Length > OriginPrefix.Length &&
                !char.IsWhiteSpace(trimmed[OriginPrefix.Length]))
            {
                continue;
            }

            var value = trimmed[OriginPrefix.Length..].Trim();
            if (Enum.TryParse<CueOrigin>(value, ignoreCase: true, out var origin) &&
                Enum.IsDefined(origin))
            {
                return origin;
            }
        }

        return null;
    }

    private static bool HasSuffix(string cuePath, string suffix)
    {
        var fileName = Path.GetFileNameWithoutExtension(cuePath);
        return fileName.EndsWith(suffix, StringComparison.OrdinalIgnoreCase);
    }
}
